const messages: Record<Locale, Record<string, string>> = { en, fr };

export function translate(
  locale: Locale,
  key: string,
  variables: Record<string, string | number> = {},
): string {
  const template = messages[locale][key] ?? messages.en[key] ?? key;
  return Object.entries(variables).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    template,
  );
}

export function translateFinding(locale: Locale, code: string, message: string): string {
  if (locale === "en") return message;
  const numbers = message.match(/-?\d+(?:\.\d+)?/g) ?? [];
  const translated: Record<string, string> = {
    loudness_unavailable:
      "Le niveau sonore intégré est indisponible ; l’assistant conserve donc le gain d’entrée.",
    loudness_target:
      numbers.length >= 2
        ? `Le niveau sonore intégré est de ${numbers[0]} LUFS ; la cible demandée est de ${numbers[1]} LUFS.`
        : "Le niveau sonore intégré est comparé à la cible demandée.",
    gain_bounded:
      numbers.length >= 2
        ? `Le gain demandé de ${numbers[0]} dB est limité à ${numbers[1]} dB par la politique de sécurité active.`
        : "Le gain demandé est limité par la politique de sécurité active.",
    peak_headroom_limited:
      numbers.length >= 1
        ? `La marge de crête mesurée n’autorise que ${numbers[0]} dB de gain avant le plafond.`
        : "Le gain est limité par la marge de crête mesurée.",
    stereo_evidence_unavailable:
      "Les mesures stéréo sont indisponibles ; aucune recommandation de traitement stéréo n’est formulée.",
    phase_warning:
      "Une corrélation de phase négative a été mesurée ; conservez la largeur stéréo jusqu’à vérification.",
  };
  return translated[code] ?? message;
}

export function translateApiError(locale: Locale, message: string): string {
  if (locale === "en") return message;
  const httpStatus = message.match(/non-JSON response \(HTTP (\d+)\)/)?.[1];
  if (httpStatus) return translate(locale, "nonJsonError", { status: httpStatus });
  if (/networkerror|failed to fetch|load failed/i.test(message)) {
    return translate(locale, "networkError");
  }
  if (message === "Invalid mastering password") {
    return locale === "fr" ? "Mot de passe de mastering incorrect." : message;
  }
  if (message === "Mastering access is not configured") {
    return locale === "fr"
      ? "Le mot de passe de mastering n’est pas configuré sur le serveur."
      : message;
  }
  return message;
}

export function translateMusicalKey(locale: Locale, value: string): string {
  if (locale === "en") return value;
  return value.replace(/\bminor\b/gi, "mineur").replace(/\bmajor\b/gi, "majeur");
}
